import { cva, type VariantProps } from "class-variance-authority"
import { cn } from "cn";



// Use of cva() in order to create a reusable card component with variants for styling in case they are needed in the future.
export const cardVariants = cva(

    "inline-block border border-solid rounded-2xl overflow-hidden",
    {
        variants: {
            variant: {
                default: "border-black shadow-md p-2 m-1.5 bg-white",
            },
            size: {
                default: "w-sm h-sm max-h-32",
            }
        },
        defaultVariants: {
            variant: "default",
            size: "default"
        }
    }

);

interface CardComponentProps extends React.HTMLAttributes<HTMLDivElement>, VariantProps<typeof cardVariants> {
    //children: React.ReactNode;
}

// ...props spreads the rest of the props that are passed to the component that have not explicitly been defined in the arguments of the component. It is not a separate literal object.
export const CardComponent = ({ children, variant, size, className, ...props }: CardComponentProps) => {
// 'className' passed as a prop is the className that is passed to the component when it is used in another component, which means it is concatenated with the className that is generated by the cardVariants function. It can be called however you want, but it is a common convention to call it className given the official docu from cn()
// 'children' must be passed as a prop to the component in order to be rendered inside the card. It is a special prop that is automatically passed to every component in React, and it can be used to render any content inside the component. It is not a separate literal object.
    return (
        <div className={cn(cardVariants({variant, size}), className)} {...props}>
            <div className="text-wrap overflow-y-auto h-28">
                {children}
            </div>
        </div>
    )
}